CREATE TABLE public.usuarios (
    idusuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    usuario varchar(50) NOT NULL UNIQUE,
    contrasena varchar(255) NOT NULL,
    rol varchar(50) NOT NULL DEFAULT 'Administrador'
);

CREATE TABLE public.clientes (
    idcliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    telefono varchar(10) NOT NULL,
    correo varchar(255),
    direccion varchar(500),
    observaciones varchar(1000)
);

CREATE TABLE public.productos (
    idproducto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    categoria varchar(50) NOT NULL,
    tipo_crema varchar(50) NOT NULL,
    porciones varchar(20) NOT NULL,
    precio_base numeric(10,2) NOT NULL
);

CREATE TABLE public.proveedores (
    idproveedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    telefono varchar(10) NOT NULL,
    correo varchar(255),
    direccion varchar(500),
    productos_suministrados varchar(1000) NOT NULL,
    observaciones varchar(1000)
);

CREATE TABLE public.pedidos (
    idpedido integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idcliente integer NOT NULL REFERENCES public.clientes(idcliente),
    fecha_pedido date NOT NULL DEFAULT CURRENT_DATE,
    fecha_entrega date NOT NULL,
    hora_entrega time without time zone,
    tipo_entrega varchar(50) NOT NULL,
    direccion_entrega varchar(1000),
    estado varchar(50) NOT NULL DEFAULT 'Pendiente',
    observaciones varchar(1000),
    total numeric(10,2) NOT NULL,
    anticipo numeric(10,2) DEFAULT 0,
    saldo numeric(10,2) NOT NULL,
    imagen_referencia varchar(255)
);

CREATE TABLE public.detalle_pedido (
    iddetalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idpedido integer NOT NULL REFERENCES public.pedidos(idpedido) ON DELETE CASCADE,
    descripcion varchar(1000),
    cantidad integer NOT NULL,
    precio_unitario numeric(10,2) NOT NULL,
    subtotal numeric(10,2) NOT NULL,
    idproducto integer NOT NULL REFERENCES public.productos(idproducto),
    extras varchar(500),
    valor_extras numeric(10,2) DEFAULT 0
);

